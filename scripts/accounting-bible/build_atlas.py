#!/usr/bin/env python3
"""Generate docs/accounting-bible/03-code-anchor-atlas.md (and 03b-schema-atlas.md).

Never hand-edit the generated parts. Re-run from the repo root:
    python3 scripts/accounting-bible/build_atlas.py

What it records, per module of the accounting branch and its feeders:
  * line count, git commit
  * every `export` with its line number (the PIN)
  * production importers (non-test files that import the module) -> rule 50
  * test importers
And for the schema: every gl_* SQL function with file:line, which migration
last redefined it, and every application call site (`rpc("gl_...")`).
"""
import os
import re
import subprocess
from collections import defaultdict

ROOT = os.getcwd()
OUT_DIR = os.path.join(ROOT, "docs", "accounting-bible")
COMMIT = subprocess.check_output(["git", "rev-parse", "HEAD"], text=True).strip()

MODULE_DIRS = [
    "src/lib/accounting",
    "src/lib/plaid",
    "src/lib/loans",
    "src/lib/atm",
    "src/lib/registers",
]
# feeders we only list exports for posting-relevant files
FEEDER_GLOBS = [
    ("src/lib/payroll", re.compile(r"(posting|gl|ledger|journal|form-941|form-940|deposit|liabilit)", re.I)),
    ("src/lib/payments", re.compile(r"(ach|vendor-reconcile|nacha|settle)", re.I)),
    ("src/lib/purchasing", re.compile(r"(manifest|receiv|bill|invoice)", re.I)),
    ("src/lib/reports", re.compile(r"(net-income|wa-tax|accounting|sage|revenue|cogs)", re.I)),
    ("src/lib/compliance", re.compile(r"(excise|wa-tax)", re.I)),
]

EXPORT_RE = re.compile(
    r"^export\s+(?:default\s+)?(?:async\s+)?(function\*?|const|let|class|type|interface|enum)\s+([A-Za-z0-9_$]+)"
)
EXPORT_BRACE_RE = re.compile(r"^export\s*\{([^}]*)\}")


def all_src_files():
    files = []
    for base in ["src", "scripts", "tests"]:
        for dp, dn, fn in os.walk(os.path.join(ROOT, base)):
            if "node_modules" in dp:
                continue
            for f in fn:
                if f.endswith((".ts", ".tsx", ".mjs", ".js")):
                    files.append(os.path.relpath(os.path.join(dp, f), ROOT))
    return files


SRC = all_src_files()
CONTENT = {}
for f in SRC:
    try:
        with open(os.path.join(ROOT, f), encoding="utf-8", errors="replace") as h:
            CONTENT[f] = h.read()
    except OSError:
        CONTENT[f] = ""


def is_test(path):
    return "__tests__" in path or path.startswith("tests/") or ".test." in path or path.startswith("scripts/")


def importers_of(mod_path):
    stem = os.path.splitext(os.path.basename(mod_path))[0]
    alias = "@/" + os.path.splitext(mod_path[len("src/"):])[0] if mod_path.startswith("src/") else None
    pat = re.compile(
        r"""from\s+["']([^"']*/%s)["']|import\(\s*["']([^"']*/%s)["']\s*\)""" % (re.escape(stem), re.escape(stem))
    )
    prod, test = [], []
    for f, c in CONTENT.items():
        if f == mod_path:
            continue
        hit = False
        for m in pat.finditer(c):
            spec = m.group(1) or m.group(2)
            if alias and spec == alias:
                hit = True
            elif spec.startswith("."):
                resolved = os.path.normpath(os.path.join(os.path.dirname(f), spec))
                if resolved == os.path.splitext(mod_path)[0]:
                    hit = True
        if hit:
            (test if is_test(f) else prod).append(f)
    return sorted(prod), sorted(test)


def exports_of(path):
    out = []
    for i, line in enumerate(CONTENT.get(path, "").splitlines(), 1):
        m = EXPORT_RE.match(line)
        if m:
            out.append((i, m.group(1), m.group(2)))
            continue
        m = EXPORT_BRACE_RE.match(line)
        if m:
            out.append((i, "re-export", m.group(1).strip()[:80]))
    return out


def module_list():
    mods = []
    for d in MODULE_DIRS:
        for f in sorted(SRC):
            if f.startswith(d + "/") and "__tests__" not in f and f.endswith((".ts", ".tsx")):
                mods.append(f)
    for d, rx in FEEDER_GLOBS:
        for f in sorted(SRC):
            if f.startswith(d + "/") and "__tests__" not in f and rx.search(os.path.basename(f)):
                mods.append(f)
    return mods


def write_code_atlas():
    mods = module_list()
    lines = []
    w = lines.append
    w("# Part 03 — Code Anchor Atlas (GENERATED — do not hand-edit)")
    w("")
    w(f"Generated by `scripts/accounting-bible/build_atlas.py` at commit `{COMMIT}`.")
    w("")
    w("**How to use:** search for a symbol, read its `file:line` PIN, then open the file *at that line*.")
    w("Before you edit anything, run `git diff %s -- <file>`. If the file moved, regenerate this part." % COMMIT[:8])
    w("")
    w("Columns: `prod importers` = non-test files that import the module. **0 prod importers = dead code under rule 50**")
    w("(unless it is a pure `*-core.ts` consumed only by a `*-service.ts` you plan to build, or a page/route).")
    w("Pages, routes and server actions (`src/app/**`) are entry points; they have no importers by design.")
    w("")
    # summary table
    w("## A. Module census (every module, one row)")
    w("")
    w("| # | module | lines | exports | prod importers | test importers | status |")
    w("|---|---|---:|---:|---:|---:|---|")
    details = []
    total_lines = 0
    dead = []
    for n, m in enumerate(mods, 1):
        c = CONTENT.get(m, "")
        lc = c.count("\n") + (0 if c.endswith("\n") or not c else 1)
        total_lines += lc
        ex = exports_of(m)
        prod, test = importers_of(m)
        status = "LIVE" if prod else ("TEST-ONLY (rule 50: dead)" if test else "ORPHAN (no importers)")
        if not prod:
            dead.append(m)
        w(f"| {n} | `{m}` | {lc} | {len(ex)} | {len(prod)} | {len(test)} | {status} |")
        details.append((m, lc, ex, prod, test))
    w("")
    w(f"Totals: {len(mods)} modules, {total_lines} lines. Not imported by production code: {len(dead)}.")
    w("")
    w("## B. Not imported by production code (rule 50 watch list)")
    w("")
    w("A pure core consumed only by tests is *not yet wired*. Every row here is either (a) a planned")
    w("feeder awaiting its service (see Part 09 slice plan), (b) a library of constants/authorities")
    w("read only by tests (acceptable if it says so), or (c) genuinely dead. Part 04 classifies them.")
    w("")
    for m in dead:
        w(f"- `{m}`")
    w("")
    w("## C. Per-module export pins")
    w("")
    for m, lc, ex, prod, test in details:
        w(f"### `{m}` ({lc} lines)")
        w("")
        if prod:
            w("prod importers: " + ", ".join(f"`{p}`" for p in prod[:25]) + (" …" if len(prod) > 25 else ""))
        else:
            w("prod importers: **none**")
        if test:
            w("")
            w("test importers: " + ", ".join(f"`{t}`" for t in test[:10]) + (" …" if len(test) > 10 else ""))
        w("")
        if ex:
            w("| line | kind | symbol |")
            w("|---:|---|---|")
            for ln, kind, sym in ex:
                w(f"| {ln} | {kind} | `{sym}` |")
        else:
            w("_(no top-level exports)_")
        w("")
    os.makedirs(OUT_DIR, exist_ok=True)
    with open(os.path.join(OUT_DIR, "03-code-anchor-atlas.md"), "w") as h:
        h.write("\n".join(lines) + "\n")
    return len(lines)


FN_RE = re.compile(r"create\s+(?:or\s+replace\s+)?function\s+(?:public\.)?(gl_[a-z0-9_]+)\s*\(", re.I)
TABLE_RE = re.compile(r"create\s+table\s+(?:if\s+not\s+exists\s+)?(?:public\.)?([a-z0-9_]+)", re.I)
TRIGGER_RE = re.compile(r"create\s+(?:constraint\s+)?trigger\s+([a-z0-9_]+)", re.I)


def write_schema_atlas():
    mig_dir = os.path.join(ROOT, "supabase", "migrations")
    migs = sorted(f for f in os.listdir(mig_dir) if f.endswith(".sql"))
    fns = defaultdict(list)
    tables = defaultdict(list)
    triggers = defaultdict(list)
    for mg in migs:
        with open(os.path.join(mig_dir, mg), encoding="utf-8", errors="replace") as h:
            for i, line in enumerate(h, 1):
                for m in FN_RE.finditer(line):
                    fns[m.group(1)].append((mg, i))
                m = TABLE_RE.search(line)
                if m and (m.group(1).startswith(("gl_", "bank_", "vendor_bill", "payroll_run", "fixed_asset",
                                                  "deposit_", "atm_", "plaid_", "loan", "manual_loan",
                                                  "ach_", "register_", "safe_", "supply_run", "drawer"))):
                    tables[m.group(1)].append((mg, i))
                m = TRIGGER_RE.search(line)
                if m and mg >= "0172":
                    triggers[m.group(1)].append((mg, i))
    lines = []
    w = lines.append
    w("# Part 03b — Schema Atlas (GENERATED — do not hand-edit)")
    w("")
    w(f"Generated by `scripts/accounting-bible/build_atlas.py` at commit `{COMMIT}`.")
    w("")
    w("## A. Every `gl_*` SQL function: definitions (all redefinitions), and app call sites")
    w("")
    w("The **last** definition listed is the live one (migrations apply in order). `app callers` counts")
    w("`rpc(\"gl_x\")` / `rpc('gl_x')` occurrences in non-test `src/**`. Trigger functions are called by")
    w("triggers, not by the app, so 0 is expected for `gl_guard_*`, `gl_ob_*`, `*_append_only`.")
    w("")
    w("| function | defined at (file:line, in order) | live def | app callers |")
    w("|---|---|---|---|")
    rpc_hits = {}
    for fn in sorted(fns):
        rx = re.compile(r"""rpc\(\s*["'`]%s["'`]""" % fn)
        callers = []
        for f, c in CONTENT.items():
            if f.startswith("src/") and not is_test(f):
                for i, line in enumerate(c.splitlines(), 1):
                    if rx.search(line):
                        callers.append(f"{f}:{i}")
        rpc_hits[fn] = callers
        defs = "<br>".join(f"`{m}:{l}`" for m, l in fns[fn])
        live = f"`{fns[fn][-1][0]}:{fns[fn][-1][1]}`"
        cs = "<br>".join(f"`{c}`" for c in callers) if callers else "**0**"
        w(f"| `{fn}` | {defs} | {live} | {cs} |")
    w("")
    writers = [f for f in fns if re.match(r"gl_(post|reverse|close|reopen|bless|submit|approve|mark|upsert|set|open|bank_reconcile|sign_off|unmatch|factory_reset$)", f)]
    w("## B. Writer RPCs with ZERO application callers (the connection gap, mechanically)")
    w("")
    for fn in sorted(writers):
        if not rpc_hits.get(fn):
            m, l = fns[fn][-1]
            w(f"- `{fn}` — live def `{m}:{l}` — **no `rpc()` call in src/**")
    w("")
    w("## C. Ledger-adjacent tables (first `create table` site)")
    w("")
    w("| table | created at |")
    w("|---|---|")
    for t in sorted(tables):
        m, l = tables[t][0]
        w(f"| `{t}` | `{m}:{l}` |")
    w("")
    w("## D. Triggers created in migrations ≥ 0172")
    w("")
    w("| trigger | created at |")
    w("|---|---|")
    for t in sorted(triggers):
        locs = "<br>".join(f"`{m}:{l}`" for m, l in triggers[t])
        w(f"| `{t}` | {locs} |")
    w("")
    with open(os.path.join(OUT_DIR, "03b-schema-atlas.md"), "w") as h:
        h.write("\n".join(lines) + "\n")
    return len(lines)


if __name__ == "__main__":
    a = write_code_atlas()
    b = write_schema_atlas()
    print(f"03-code-anchor-atlas.md lines={a}  03b-schema-atlas.md lines={b}  commit={COMMIT[:8]}")

/** File extension written to storage for each type (app-generated name). */
export const STORAGE_EXT: Readonly<Record<DocMime, string>> = {
  "application/pdf": "pdf",
  "image/jpeg": "jpg",
  "image/png": "png",
  "image/heic": "heic",
};

/** Extensions a person's file may carry for each sniffed type. */
export const ALLOWED_EXTS: Readonly<Record<DocMime, readonly string[]>> = {
  "application/pdf": ["pdf"],
  "image/jpeg": ["jpg", "jpeg"],
  "image/png": ["png"],
  "image/heic": ["heic", "heif", "hif"],
};

/** Declared types a browser may send for each sniffed type ("" = unknown). */
const DECLARED_OK: Readonly<Record<DocMime, readonly string[]>> = {
  "application/pdf": ["application/pdf", "application/x-pdf"],
  "image/jpeg": ["image/jpeg", "image/jpg", "image/pjpeg"],
  "image/png": ["image/png"],
  "image/heic": ["image/heic", "image/heif"],
};
const DECLARED_UNKNOWN = ["", "application/octet-stream", "binary/octet-stream"];

/**
 * Inner extensions that mean "this is really a program or a page" — a name
 * like statement.php.pdf or check.html.png is refused (OWASP double extension).
 */
const DANGEROUS_INNER_EXTS = new Set([
  "php", "php3", "php4", "php5", "phtml", "phar", "asp", "aspx", "jsp", "jspx", "cgi", "pl", "py", "rb",
  "sh", "bash", "bat", "cmd", "com", "exe", "dll", "msi", "scr", "ps1", "vbs", "vbe", "js", "mjs", "jar",
  "html", "htm", "xhtml", "svg", "xml", "hta", "lnk", "app", "dmg",
]);

// ------------------------------------------------------------- signature ----

const HEIC_BRANDS = new Set(["heic", "heix", "heim", "heis"]);

function ascii(bytes: Uint8Array, start: number, len: number): string {
  let s = "";
  for (let i = start; i < start + len && i < bytes.length; i += 1) s += String.fromCharCode(bytes[i]);
  return s;
}

/**
 * Identify the file from its first bytes. Returns null for anything that is
 * not one of the four allowed types — the caller refuses it.
 *   PDF  "%PDF-" at 0 (ISO 32000 header; all five bytes required)
 *   PNG  89 50 4E 47 0D 0A 1A 0A at 0
 *   JPEG FF D8 FF at 0
 *   HEIC "ftyp" at 4 and a heic/heix/heim/heis brand inside the ftyp box
 */
export function sniffDocMime(bytes: Uint8Array): DocMime | null {
  if (bytes.length >= 5 && ascii(bytes, 0, 5) === "%PDF-") return "application/pdf";
  const png = [0x89, 0x50, 0x4e, 0x47, 0x0d, 0x0a, 0x1a, 0x0a];
  if (bytes.length >= 8 && png.every((b, i) => bytes[i] === b)) return "image/png";
  if (bytes.length >= 3 && bytes[0] === 0xff && bytes[1] === 0xd8 && bytes[2] === 0xff) return "image/jpeg";
  if (bytes.length >= 12 && ascii(bytes, 4, 4) === "ftyp") {
    const boxLen = ((bytes[0] << 24) >>> 0) + (bytes[1] << 16) + (bytes[2] << 8) + bytes[3];
    // major brand at 8; minor version at 12..15; compatible brands from 16.
    if (HEIC_BRANDS.has(ascii(bytes, 8, 4))) return "image/heic";
    const end = Math.min(boxLen >= 16 ? boxLen : 0, bytes.length, 4096);
    for (let off = 16; off + 4 <= end; off += 4) {
      if (HEIC_BRANDS.has(ascii(bytes, off, 4))) return "image/heic";
    }
  }
  return null;
}

// -------------------------------------------------------------- filename ----

export type FilenameCheck =
  | { ok: true; display: string; ext: string }
  | { ok: false; refusal: string };

/**
 * Check the person's file name. It is never used as a storage key; it is kept
 * as display text, so it must be printable, short and not misleading.
 */
export function checkOriginalFilename(raw: string | null | undefined): FilenameCheck {
  const name = String(raw ?? "");
  // eslint-disable-next-line no-control-regex
  if (/[\u0000-\u001f\u007f]/.test(name)) return { ok: false, refusal: "The file name has hidden control characters. Rename the file and try again." };
  // OWASP: "reject any filename containing a colon" - checked on the raw name,
  // so a Windows path (C:\...) or an NTFS stream (x.pdf:evil) is refused too.
  if (name.includes(":")) return { ok: false, refusal: "File names may not contain a colon (:). Rename the file and try again." };
  // Browsers send only the base name, but strip any path a client might add.
  const base = name.split(/[\\/]/).pop()!.trim();
  if (!base) return { ok: false, refusal: "The file has no name. Rename it (for example signed-form.pdf) and try again." };
  if (base.length > MAX_ORIGINAL_FILENAME_CHARS) {
    return { ok: false, refusal: `The file name is longer than ${MAX_ORIGINAL_FILENAME_CHARS} characters. Shorten it and try again.` };
  }
  const parts = base.split(".");
  if (parts.length < 2 || !parts[parts.length - 1]) {
    return { ok: false, refusal: "The file name has no extension. Upload a .pdf, .jpg, .png or .heic file." };
  }
  const ext = parts[parts.length - 1].toLowerCase();
  for (const inner of parts.slice(1, -1)) {
    if (DANGEROUS_INNER_EXTS.has(inner.toLowerCase())) {
      return { ok: false, refusal: `The file name hides a ".${inner}" extension inside it. Rename the file and try again.` };
    }
  }
  return { ok: true, display: base, ext };
}


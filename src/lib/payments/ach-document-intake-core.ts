export type UploadInput = {
  bytes: Uint8Array;
  declaredMime: string | null | undefined;
  filename: string | null | undefined;
  kind: string | null | undefined;
};

export type UploadVerdict =
  | { ok: true; mime: DocMime; kind: DocKind; ext: string; displayName: string; byteSize: number }
  | { ok: false; refusal: string };

function sizeLabel(n: number): string {
  return `${(n / (1024 * 1024)).toFixed(1)} MB`;
}

/** Decide whether one dropped file may be stored. Pure: no hashing, no I/O. */
export function checkDocumentUpload(input: UploadInput): UploadVerdict {
  const kind = String(input.kind ?? "") as DocKind;
  if (!UPLOADABLE_DOC_KINDS.includes(kind)) {
    return { ok: false, refusal: "Pick what the document is: signed form, voided check, bank letter, or other." };
  }
  const size = input.bytes.length;
  if (size <= 0) return { ok: false, refusal: "The file is empty. Pick the file again." };
  if (size > MAX_DOC_BYTES) {
    return { ok: false, refusal: `The file is ${sizeLabel(size)}; the limit is 25 MB. Scan at a lower resolution or upload a PDF.` };
  }
  const name = checkOriginalFilename(input.filename);
  if (!name.ok) return name;
  const mime = sniffDocMime(input.bytes);
  if (!mime) {
    return { ok: false, refusal: "This file is not a PDF, JPEG, PNG or HEIC (checked from the file itself, not its name). Upload a scan or photo in one of those formats." };
  }
  if (!ALLOWED_EXTS[mime].includes(name.ext)) {
    return {
      ok: false,
      refusal: `The file is really a ${STORAGE_EXT[mime].toUpperCase()} but is named ".${name.ext}". Rename it to .${STORAGE_EXT[mime]} and try again.`,
    };
  }
  const declared = String(input.declaredMime ?? "").trim().toLowerCase();
  if (!DECLARED_UNKNOWN.includes(declared) && !DECLARED_OK[mime].includes(declared)) {
    return { ok: false, refusal: `The browser says this file is "${declared}" but its contents are ${STORAGE_EXT[mime].toUpperCase()}. Re-save the file and try again.` };
  }
  return { ok: true, mime, kind, ext: STORAGE_EXT[mime], displayName: name.display, byteSize: size };
}

const UUID_RE = /^[0-9a-f]{8}-[0-9a-f]{4}-[1-8][0-9a-f]{3}-[89ab][0-9a-f]{3}-[0-9a-f]{12}$/;

export type PayeeType = "employee" | "vendor";

/**
 * App-generated storage location. `objectKey` is the key inside the ach-docs
 * bucket; `storagePath` is what the table stores (0258: like 'ach-docs/%').
 */
export function planDocumentPath(input: { payeeType: PayeeType; payeeId: string; fileUuid: string; mime: DocMime }):
  | { ok: true; objectKey: string; storagePath: string }
  | { ok: false; refusal: string } {
  if (input.payeeType !== "employee" && input.payeeType !== "vendor") return { ok: false, refusal: "Unknown payee type." };
  const payeeId = input.payeeId.toLowerCase();
  const fileUuid = input.fileUuid.toLowerCase();
  if (!UUID_RE.test(payeeId)) return { ok: false, refusal: "Unknown payee." };
  if (!UUID_RE.test(fileUuid)) return { ok: false, refusal: "Could not name the file." };
  const objectKey = `${input.payeeType}/${payeeId}/${fileUuid}.${STORAGE_EXT[input.mime]}`;
  return { ok: true, objectKey, storagePath: `ach-docs/${objectKey}` };
}

export function isSha256Hex(s: string): boolean {
  return /^[0-9a-f]{64}$/.test(s);
}


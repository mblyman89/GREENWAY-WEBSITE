/**
 * R39 S5 — ACH document intake (pure; no I/O).
 *
 * Owner answers this implements:
 *   Q2  "managers upload documents; enterprise grade" — drop-only intake.
 *   Q6  "LlamaParse" — a machine DRAFT only; a person always re-keys blind.
 *   Q10 the signed form goes in the employee file AND the vault.
 *
 * Every limit below mirrors a CHECK in supabase/migrations/0258 (pinned by
 * tests/compliance/r39-ach-document-intake.test.ts) so the app refuses a file
 * with a plain sentence before Postgres would refuse it with a code.
 *
 * Upload rules follow the OWASP File Upload Cheat Sheet
 * (cheatsheetseries.owasp.org/cheatsheets/File_Upload_Cheat_Sheet.html):
 *   - "Validate the file type, don't trust the Content-Type header" -> the
 *     magic bytes decide; a declared type that disagrees is refused.
 *   - signature validation "should not be used on its own" -> the extension
 *     must ALSO be allow-listed and agree with the bytes.
 *   - "Change the filename to something generated by the application" ->
 *     storage key is <payee type>/<payee id>/<uuid>.<ext>; the person's file
 *     name is kept only as display text.
 *   - reject colons, null bytes / control characters, double extensions that
 *     hide an executable, and over-long names; "Set a file size limit".
 *
 * HEIC signature: ISO BMFF "ftyp" box at byte 4; the major or a compatible
 * brand must be heic / heix / heim / heis (IANA image/heic registration, as
 * summarised by Library of Congress fdd000526).
 */
import { isValidRouting } from "./nacha-core";
import { MAX_ACCOUNTS_PER_PAYEE, type AccountType, type SplitRule } from "./ach-authorization-core";


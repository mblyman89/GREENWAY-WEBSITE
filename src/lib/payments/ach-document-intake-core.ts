export type DraftAccount = {
  bankName: string;
  routing: string;
  account: string;
  accountType: AccountType | null;
  rule: SplitRule | null;
};

export type BankDraft = {
  source: "acroform" | "llamaparse" | "none";
  payeeName: string;
  signedOn: string | null;
  request: "new" | "change" | "cancel" | null;
  accounts: DraftAccount[];
  warnings: string[];
};

export const EMPTY_DRAFT: BankDraft = { source: "none", payeeName: "", signedOn: null, request: null, accounts: [], warnings: [] };

export type FormFields = Readonly<Record<string, string | boolean | null | undefined>>;

function fStr(f: FormFields, k: string): string {
  const v = f[k];
  return typeof v === "string" ? v.trim() : "";
}
/** pdf.js reports a ticked box as its export value ("Yes" on our forms) or true. */
function fOn(f: FormFields, k: string): boolean {
  const v = f[k];
  if (v === true) return true;
  if (typeof v !== "string") return false;
  const t = v.trim();
  return t !== "" && t !== "Off" && t.toLowerCase() !== "false";
}

/**
 * "$1,200.50" -> fixed 120050 cents; "25%" -> 2500 bp; "12.5 %" -> 1250 bp.
 * Blank -> null. Anything else -> an error sentence (never a guess).
 */
export function parseAmountRule(text: string): { ok: true; rule: SplitRule | null } | { ok: false; error: string } {
  const t = text.trim();
  if (!t) return { ok: true, rule: null };
  const pct = /^(\d{1,2}(?:\.\d{1,2})?)\s*%$/.exec(t);
  if (pct) {
    const bp = Math.round(Number(pct[1]) * 100);
    if (bp <= 0 || bp >= 10000) return { ok: false, error: `"${t}" must be more than 0% and less than 100%.` };
    return { ok: true, rule: { kind: "percent", basisPoints: bp } };
  }
  const money = /^\$?\s*(\d{1,3}(?:,\d{3})+|\d+)(?:\.(\d{1,2}))?$/.exec(t);
  if (money) {
    const dollars = Number(money[1].replace(/,/g, ""));
    const cents = dollars * 100 + Number((money[2] ?? "0").padEnd(2, "0"));
    if (!Number.isSafeInteger(cents) || cents <= 0) return { ok: false, error: `"${t}" must be more than $0.` };
    return { ok: true, rule: { kind: "fixed", cents } };
  }
  return { ok: false, error: `"${t}" is not a dollar amount (like $200.00) or a percentage (like 25%).` };
}

function typeFrom(checking: boolean, savings: boolean, label: string, warnings: string[]): AccountType | null {
  if (checking && savings) {
    warnings.push(`${label}: both checking and savings are ticked.`);
    return null;
  }
  return checking ? "checking" : savings ? "savings" : null;
}

function digits(s: string): string {
  return s.replace(/[\s-]/g, "");
}

function requestFrom(n: boolean, c: boolean, x: boolean, warnings: string[]): BankDraft["request"] {
  const count = [n, c, x].filter(Boolean).length;
  if (count > 1) {
    warnings.push("More than one request type (new / change / cancel) is ticked.");
    return null;
  }
  return n ? "new" : c ? "change" : x ? "cancel" : null;
}

/**
 * Flatten pdf.js getFieldObjects() output ({ name: [widget, ...] }) into the
 * plain map draftFromAcroForm reads. Only text, checkbox and radio widgets
 * count (signature widgets are ignored). When a name has several widgets, the
 * first one that is filled / ticked wins; a name whose widgets DISAGREE
 * (two different filled values) is reported, never resolved by guessing.
 */
export function fieldsFromFieldObjects(raw: unknown): { fields: Record<string, string | boolean>; conflicts: string[] } {
  const fields: Record<string, string | boolean> = {};
  const conflicts: string[] = [];
  if (!raw || typeof raw !== "object") return { fields, conflicts };
  for (const [name, widgets] of Object.entries(raw as Record<string, unknown>)) {
    if (!Array.isArray(widgets) || !/^[A-Za-z0-9_]{1,64}$/.test(name)) continue;
    const seen: (string | boolean)[] = [];
    for (const w of widgets) {
      const o = (w ?? {}) as { type?: unknown; value?: unknown };
      if (o.type !== "text" && o.type !== "checkbox" && o.type !== "radiobutton") continue;
      const v = o.value;
      if (typeof v === "boolean") { if (v) seen.push(true); continue; }
      if (typeof v !== "string") continue;
      const t = v.trim();
      if (t === "" || t === "Off") continue;
      seen.push(t.slice(0, 200));
    }
    if (seen.length === 0) continue;
    if (new Set(seen.map(String)).size > 1) conflicts.push(name);
    else fields[name] = seen[0];
  }
  return { fields, conflicts };
}

/** Which of OUR fillable forms these fields came from (by field names), or null. */
export function acroFormKind(raw: unknown): PayeeType | null {
  if (!raw || typeof raw !== "object") return null;
  const names = Object.keys(raw as object);
  const emp = ["e_legal_name", "e_a1_rtn", "e_a1_acct"].every((n) => names.includes(n));
  const ven = ["v_legal_name", "v_rtn", "v_acct", "v_acct2"].every((n) => names.includes(n));
  if (emp === ven) return null;
  return emp ? "employee" : "vendor";
}

/**
 * Map the AcroForm fields of OUR fillable forms (field names read from
 * Greenway-Employee-Direct-Deposit-Authorization-FILLABLE.pdf and
 * Greenway-Vendor-ACH-Authorization-FILLABLE.pdf) into a draft. Every
 * problem becomes a warning; nothing is corrected silently.
 */
export function draftFromAcroForm(payeeType: PayeeType, f: FormFields): BankDraft {
  const warnings: string[] = [];
  const accounts: DraftAccount[] = [];
  if (payeeType === "employee") {
    for (let i = 1; i <= MAX_ACCOUNTS_PER_PAYEE; i += 1) {
      const p = `e_a${i}_`;
      const bankName = fStr(f, `${p}bank`);
      const routing = digits(fStr(f, `${p}rtn`));
      const account = digits(fStr(f, `${p}acct`));
      const amt = fStr(f, `${p}amt`);
      const rem = fOn(f, `${p}rem`);
      const chk = fOn(f, `${p}chk`);
      const sav = fOn(f, `${p}sav`);
      if (!bankName && !routing && !account && !amt && !rem && !chk && !sav) continue;
      const label = `Account ${i}`;
      const accountType = typeFrom(chk, sav, label, warnings);
      let rule: SplitRule | null = null;
      const parsed = parseAmountRule(amt);
      if (!parsed.ok) warnings.push(`${label}: ${parsed.error}`);
      if (rem && parsed.ok && parsed.rule) warnings.push(`${label}: both an amount and "remainder" are filled in.`);
      else if (rem) rule = { kind: "remainder" };
      else if (parsed.ok) rule = parsed.rule;
      if (!rule && !(rem && parsed.ok && parsed.rule)) warnings.push(`${label}: no amount, percentage or remainder is filled in.`);
      if (routing && !isValidRouting(routing)) warnings.push(`${label}: routing number fails the ABA check digit.`);
      if (!routing) warnings.push(`${label}: routing number is blank.`);
      if (!account) warnings.push(`${label}: account number is blank.`);
      if (!accountType && !(chk && sav)) warnings.push(`${label}: checking or savings is not ticked.`);
      accounts.push({ bankName, routing, account, accountType, rule });
    }
    if (accounts.length && accounts.filter((a) => a.rule?.kind === "remainder").length !== 1) {
      warnings.push("Exactly one account should receive the remainder of net pay.");
    }
    if (fOn(f, "e_pay_chk") && !fOn(f, "e_pay_dd")) warnings.push("The employee chose a paper check, not direct deposit.");
    return {
      source: "acroform",
      payeeName: fStr(f, "e_legal_name"),
      signedOn: fStr(f, "e_e_date") || null,
      request: requestFrom(fOn(f, "e_rq_new"), fOn(f, "e_rq_chg"), fOn(f, "e_rq_can"), warnings),
      accounts,
      warnings,
    };
  }
  const routing = digits(fStr(f, "v_rtn"));
  const account = digits(fStr(f, "v_acct"));
  const confirm = digits(fStr(f, "v_acct2"));
  const bankName = fStr(f, "v_bank");
  const accountType = typeFrom(fOn(f, "v_at_chk"), fOn(f, "v_at_sav"), "Account", warnings);
  if (routing || account || bankName) {
    if (!routing) warnings.push("Routing number is blank.");
    else if (!isValidRouting(routing)) warnings.push("Routing number fails the ABA check digit.");
    if (!account) warnings.push("Account number is blank.");
    if (account && confirm && account !== confirm) warnings.push("The account number and its confirmation on the form do not match.");
    if (account && !confirm) warnings.push("The account number confirmation box is blank.");
    if (!accountType && !(fOn(f, "v_at_chk") && fOn(f, "v_at_sav"))) warnings.push("Checking or savings is not ticked.");
    accounts.push({ bankName, routing, account, accountType, rule: { kind: "remainder" } });
  }
  return {
    source: "acroform",
    payeeName: fStr(f, "v_legal_name"),
    signedOn: fStr(f, "v_v_date") || null,
    request: requestFrom(fOn(f, "v_rq_new"), fOn(f, "v_rq_chg"), fOn(f, "v_rq_can"), warnings),
    accounts,
    warnings,
  };
}

/**
 * Text (LlamaParse markdown of a scan / photo) -> routing-number CANDIDATES.
 * Only 9-digit runs that pass the ABA check digit count. The draft never
 * fills an account number from free text: a check's MICR line is too easy to
 * misread, and the blind re-key is the control. Candidates are hints only.
 */
export function routingCandidatesFromText(text: string): string[] {
  const out: string[] = [];
  const re = /(?<!\d)(\d{9})(?!\d)/g;
  let m: RegExpExecArray | null;
  while ((m = re.exec(text)) !== null) {
    if (isValidRouting(m[1]) && !out.includes(m[1])) out.push(m[1]);
  }
  return out;
}

export function draftFromParsedText(text: string): BankDraft {
  const routes = routingCandidatesFromText(text);
  const warnings = ["Read by LlamaParse from a scan. Treat every value as a guess until the blind re-key matches."];
  if (routes.length > 1) warnings.push(`More than one possible routing number was found (${routes.length}).`);
  if (routes.length === 0) warnings.push("No valid routing number was found in the scan.");
  return {
    source: "llamaparse",
    payeeName: "",
    signedOn: null,
    request: null,
    accounts: routes.length === 1 ? [{ bankName: "", routing: routes[0], account: "", accountType: null, rule: null }] : [],
    warnings,
  };
}


/** 25 MiB — 0258: byte_size > 0 and byte_size <= 26214400. */
export const MAX_DOC_BYTES = 26214400;
export const MAX_ORIGINAL_FILENAME_CHARS = 180;

export const DOC_MIME_TYPES = ["application/pdf", "image/jpeg", "image/png", "image/heic"] as const;
export type DocMime = (typeof DOC_MIME_TYPES)[number];


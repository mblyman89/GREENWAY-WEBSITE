describe("the countable claims are counted from the code", () => {
  it("there really are four statements, and the report's table lists all four", () => {
    expect(STATEMENT_LESSONS).toHaveLength(4);
    for (const l of STATEMENT_LESSONS) {
      // Each statement's QUESTION is the thing the report teaches him to use.
      expect(REPORT.toLowerCase()).toContain(l.statement.replace("_", " "));
    }
    expect(REPORT).toMatch(/Income statement/);
    expect(REPORT).toMatch(/Balance sheet/);
    expect(REPORT).toMatch(/Cash flow statement/);
    expect(REPORT).toMatch(/Statement of equity/);
  });

  it("the reading order really has seven steps, and the report says seven", () => {
    expect(READING_ORDER).toHaveLength(7);
    expect(REPORT).toMatch(/Seven steps|seven steps/);
    // Every step number appears as a heading in the report.
    for (const s of READING_ORDER) {
      expect(REPORT, `step ${s.step} is missing from the report`).toContain(`**Step ${s.step} —`);
    }
  });

  it("there really are seven principles, and the report promises seven", () => {
    expect(STATEMENT_PRINCIPLES).toHaveLength(7);
  });

  it("the report's claim about the scope note matches the scope note in the code", () => {
    expect(STATEMENT_SCOPE_NOTE).toMatch(/not audited/);
    expect(REPORT).toMatch(/not audited, not reviewed/);
    expect(REPORT).toMatch(/does not bind you/);
  });

  it("the test counts the report quotes are the real ones", () => {
    // If a later slice adds tests, these numbers become wrong. Better that the
    // build says so than that Michael reads a stale figure.
    const count = (rel: string) => {
      const src = readFileSync(join(ROOT, rel), "utf8");
      return (src.match(/^\s*it\(/gm) ?? []).length;
    };

    const ui = count("tests/compliance/financial-statements-ui-core.test.ts");
    const mentor = count("tests/compliance/financial-statements-reading-mentor.test.ts");
    const acct = count("tests/compliance/account-type-single-truth.test.ts");

    expect(REPORT, `ui-core test count is ${ui}`).toContain(`**${ui} tests** on the screen's decision layer`);
    expect(REPORT, `reading-mentor test count is ${mentor}`).toContain(`**${mentor} tests** on the teaching layer`);
    expect(REPORT, `account-type test count is ${acct}`).toContain(`**${acct} tests** on the account-type gate`);
  });
});


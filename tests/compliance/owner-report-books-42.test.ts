/**
 * tests/compliance/owner-report-books-42.test.ts
 *
 * THE OWNER REPORT IS HELD TO THE SAME STANDARD AS THE CODE (standing rule 66).
 *
 * One document ships with this slice:
 *
 *   docs/MICHAEL-books-42-the-financial-statements.md
 *
 * ─────────────────────────────────────────────────────────────────────────────
 * WHY THIS IS A TEST AND NOT A PROOFREAD
 * ─────────────────────────────────────────────────────────────────────────────
 * This particular report is more dangerous than most, because it is a TEACHING
 * document. Michael asked to be taught how to read his own statements, so he
 * will read this one carefully, believe it, and act on it for years. Every
 * arithmetic claim in it therefore has to be re-derived from the code that
 * produces the same figures on screen, not checked by eye.
 *
 * The argument for this file was proven inside this very slice, twice:
 *
 *   1. The worked example in the report claimed a gross margin of "47.9%".
 *      The real figure from the same inputs is 42.71%. I wrote a plausible
 *      number rather than computing one, and reading it back did not catch it.
 *      Executing it did.
 *
 *   2. The books-38 gap report went red the moment the financial statements
 *      screen was built, because its claim "nothing imports this engine" had
 *      become false. That is a gate on a DOCUMENT catching a document that had
 *      gone stale within a single slice.
 *
 * ─────────────────────────────────────────────────────────────────────────────
 * WHAT IS BEING PROTECTED
 * ─────────────────────────────────────────────────────────────────────────────
 *   1. THE WORKED EXAMPLE. Every dollar figure in the report's table is
 *      recomputed from `workedExample()` — the same function the screen uses.
 *      The report and the screen cannot show different numbers.
 *
 *   2. THE HEADLINE SENTENCE. The sentence Michael is meant to remember is
 *      generated by `theSentence()`, and the report must contain it verbatim.
 *
 *   3. THE DEFECT WRITE-UP. The report states specific wrong figures the engine
 *      produced ($13,200.00 net against $10,000.00 gross). Those are re-derived
 *      by actually running the engine without the guard. If someone fixes the
 *      engine upstream, the report's account of the bug becomes historical
 *      fiction and this test says so.
 *
 *   4. THE QUOTES. §280E and the regulations are quoted. Each fragment must
 *      resolve through the authority registry, so the report cannot quote text
 *      I invented.
 *
 *   5. THE COUNTED CLAIMS. "Four statements", "seven steps", "seven
 *      principles", and the test counts quoted in the closing section.
 *
 *   6. THE PDF SHIPPED. A markdown file Michael cannot open is not a delivery.
 */


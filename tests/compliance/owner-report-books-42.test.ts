describe("every statute the report quotes is real", () => {
  it("quotes §280E and the fragment resolves through the registry", () => {
    expect(REPORT).toContain("IRC §280E");
    expect(REPORT).toMatch(/No deduction or credit shall be allowed/);

    // Both directions: the words must exist in the registry, so the report
    // cannot quote text that was written for the report.
    const ids = ["IRC_280E", "IRC_280E_TRAFFICKING"];
    const found = ids.map((i) => findGuidanceAuthority(i)).filter(Boolean);
    expect(found.length, "no §280E authority resolves in the registry").toBeGreaterThan(0);
    const text = found.map((a) => JSON.stringify(a)).join(" ");
    expect(text).toMatch(/No deduction or credit shall be allowed/);
  });

  it("cites the regulation that makes cost of goods sold different from a deduction", () => {
    expect(REPORT).toContain("Treas. Reg. §1.61-3(a)");
    expect(REPORT).toMatch(/subtracted in \*?\*?arriving at\*?\*? income rather than deducted/i);
  });

  it("cites the physical-count requirement for inventory", () => {
    expect(REPORT).toContain("Treas. Reg. §1.471-2(d)");
    expect(REPORT).toMatch(/physical count/i);
  });

  it("cites the statute that makes the excise trust money", () => {
    expect(REPORT).toContain("RCW 69.50.535(4)");
  });
});

